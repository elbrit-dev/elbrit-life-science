// Regenerates src/lib/erp-products.ts from ERPNext (item group "Products", not disabled).
//
//   ERP_URL=https://erpnext.elbrit.org ERP_TOKEN=key:secret node scripts/sync-erp-products.mjs
//
// Read-only. Pulls ONLY fields that are safe to publish (name, composition, dosage form from the
// label claim, therapeutic class). Prices, margins, suppliers, market data and promotional fields
// (dose, clinical benefits, target doctors) are deliberately never requested.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const { ERP_URL = "https://erpnext.elbrit.org", ERP_TOKEN } = process.env;
if (!ERP_TOKEN) {
  console.error("Set ERP_TOKEN=api_key:api_secret");
  process.exit(1);
}

const params = new URLSearchParams({
  filters: JSON.stringify([["item_group", "=", "Products"], ["disabled", "=", 0]]),
  fields: JSON.stringify(["item_code", "whg_composition", "whg_label_claim", "custom_therapeutic_class"]),
  order_by: "item_code asc",
  limit_page_length: "0",
});
const res = await fetch(`${ERP_URL}/api/resource/Item?${params}`, {
  headers: { Authorization: `token ${ERP_TOKEN}` },
});
if (!res.ok) {
  console.error(`ERPNext ${res.status}: ${await res.text()}`);
  process.exit(1);
}
const { data } = await res.json();

const squash = (s) => s.replace(/\s+/g, " ").trim();
const bullets = (s) =>
  (s ?? "")
    .split("\n")
    .map((l) => squash(l.replace(/^[•*\-\s]+/, "")))
    .filter(Boolean);

/* "Each  flim coated  tablet contains :" -> "Film coated tablet". */
function dosageForm(labelClaim) {
  const m = /each\s+(.+?)\s+conta(?:ins?|is)\b/i.exec(labelClaim ?? "");
  if (!m) return null;
  let form = squash(m[1].replace(/["“”]/g, ""))
    .toLowerCase()
    .replace(/\bflim\b/g, "film")
    .replace(/\bcapusles?\b/g, "capsule")
    .replace(/\bbi-layered\b/g, "bilayered")
    .replace(/\bgastro resistant\b/g, "gastro-resistant")
    .replace(/\b(tablet|capsule)s\b/g, "$1")
    .replace(/^serving (of|per) /, "");
  if (!/(tablet|capsule)/.test(form)) return null;
  return form[0].toUpperCase() + form.slice(1);
}

const products = data.map((it) => ({
  code: squash(it.item_code).toUpperCase(),
  form: dosageForm(it.whg_label_claim),
  composition: bullets(it.whg_composition),
  classes: bullets(it.custom_therapeutic_class),
}));

const out = fileURLToPath(new URL("../src/lib/erp-products.ts", import.meta.url));
writeFileSync(
  out,
  `/* GENERATED by scripts/sync-erp-products.mjs from ERPNext — do not edit by hand.
   Synced ${new Date().toISOString().slice(0, 10)}: ${products.length} active SKUs (item group "Products"). */

export type ErpProduct = { code: string; form: string | null; composition: string[]; classes: string[] };

export const ERP_PRODUCTS: ErpProduct[] = ${JSON.stringify(products, null, 2)};
`
);
console.log(`Wrote ${products.length} products to ${out}`);
console.log(`  without dosage form: ${products.filter((p) => !p.form).map((p) => p.code).join(", ") || "none"}`);
